// 预编译：压成扁平词条数组，纯英文/数字词编译成词边界正则（避免 WB 命中 WBCC）
const COMPILED = RULES.map((rule) => ({
  id: rule.id,
  terms: [
    ...rule.strong.map((w) => [w, 2]),
    ...rule.weak.map((w) => [w, 1]),
    ...rule.entity.map((w) => [w, 2]),
  ].map(([word, weight]) => {
    const lower = word.toLowerCase()
    return IS_ASCII_WORD.test(lower)
      ? { term: lower, weight, re: new RegExp(`\\b${lower}\\b`) }
      : { term: lower, weight, sub: lower }
  }),
}))

// 词被 BLOCKERS 里的词拦掉了就没资格参与打分
function isBlocked(term, lowerTitle) {
  const blockers = BLOCKERS[term]
  if (!blockers) return false
  return blockers.some((b) => lowerTitle.includes(b.toLowerCase()))
}

/**
 * 按标题推断分类。
 * @param {string} title 热搜标题（原始，不需要预处理）
 * @param {number} [minScore] 命中分阈值，默认 MIN_SCORE；调小命中的更多但误判更多（调参用）
 * @returns {'entertainment'|'society'|'tech'|'finance'|'sports'|'gaming'|'general'}
 */
function classifyCategory(title, minScore = MIN_SCORE) {
  if (!title || typeof title !== 'string') return 'general'
  const lower = title.toLowerCase()

  let best = null
  let bestScore = 0

  for (const rule of COMPILED) {
    let score = 0
    for (const t of rule.terms) {
      const hit = t.re ? t.re.test(lower) : lower.includes(t.sub)
      if (!hit) continue
      if (isBlocked(t.term, lower)) continue
      score += t.weight
    }
    if (score === 0) continue
    const rank = CATEGORY_PRIORITY.indexOf(rule.id)
    if (score > bestScore || (score === bestScore && rank < CATEGORY_PRIORITY.indexOf(best))) {
      best = rule.id
      bestScore = score
    }
  }

  return bestScore >= minScore ? best : 'general'
}

module.exports = { classifyCategory, MIN_SCORE, CATEGORY_PRIORITY }
