// 热搜标题分类器：把标题归到 6 个分类之一，判断不出来就返回 general（综合）。
//
// 为什么需要它：微博 / 抖音 / B站 / 百度四家公开热榜接口都只返回标题、排名、热度，
// 没有任何分类字段。Day 17 切真数据起，sync 一律写死 category='general'，
// 结果列表里每条的标签都是「综合」，筛选栏那 6 个分类点下去 0 条结果。
//
// 【性质声明】这是按标题关键词做的启发式推断，是「我们的分组」，不是平台官方分类。
// 对外文案不能写成「平台官方分类」。命中不了的一律留 general —— 综合是「其他」桶，不是垃圾桶。
//
// 设计要点：
//   1. 打分制，不是「先命中先返回」。一条标题常同时命中多类
//      （「郑钦文中网夺冠 霸王茶姬赢麻了」= 体育 6 分 vs 财经 2 分），累加后取最高。
//   2. 权重：strong=2（几乎无歧义的词，如「夺冠」「跌停」）、weak=1（语境词，如「网友」「手机」）、
//      entity=2（人名 / 品牌 / 影视动漫 IP 名 / 球队名）。
//   3. 最高分 < MIN_SCORE 就返回 general。阈值越高越保守、越多条目落「综合」。
//      实测线上 180 条：阈值 1 → 59% 有分类，阈值 2 → 51%，阈值 3 → 23%。
//      取 2 是为了「宁可标综合，也不硬塞一个分类」。
//   4. 纯英文/数字词（AI、NBA、JDG）用词边界匹配，避免 WB 命中 WBCC 这类误伤。
//   5. BLOCKERS：已知歧义词的最小护栏。「苹果石头画」不是苹果公司，
//      「武林外传钱掌柜和小米相聚郑州」里的小米是角色名。宁可漏判也不误判——
//      误判比不分类更伤信任。以后再撞到新歧义词，往 BLOCKERS 里加一条即可。
//
// 维护：改词表后先跑预览脚本看命中率和抽样（见 docs/CATEGORY_CLASSIFIER.md），
// 抽样里出现误判就回退那条词，不要为了多分类而堆词。

